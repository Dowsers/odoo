# -*- coding: utf-8 -*-
import base64

from odoo import _, api, fields, models
from odoo.exceptions import ValidationError

from ..models.timesheet_cir_export import ADMIN_GROUP


class TimesheetCirExportWizard(models.TransientModel):
    _name = 'hr.timesheet.cir.export.wizard'
    _description = 'Timesheets CIR export wizard'

    @api.model
    def _year_selection(self):
        current_year = fields.Date.context_today(self).year
        return [(str(year), str(year)) for year in range(current_year - 5, current_year + 2)]

    @api.model
    def _month_selection(self):
        return [
            ('1', _('January')), ('2', _('February')), ('3', _('March')),
            ('4', _('April')), ('5', _('May')), ('6', _('June')),
            ('7', _('July')), ('8', _('August')), ('9', _('September')),
            ('10', _('October')), ('11', _('November')), ('12', _('December')),
        ]

    @api.model
    def _default_year(self):
        return str(self.env['hr.timesheet.cir.export']._default_period()[0])

    @api.model
    def _default_month(self):
        return str(self.env['hr.timesheet.cir.export']._default_period()[1])

    @api.model
    def _default_absence_tasks(self):
        return self.env['hr.timesheet.cir.export']._get_default_absence_tasks()

    year = fields.Selection(selection='_year_selection', string='Year', required=True, default=_default_year)
    month = fields.Selection(
        selection='_month_selection', string='Last month included', required=True, default=_default_month,
        help="The timesheets are exported from January 1st to the end of this month "
             "(by default: the previous complete month).")
    date_from = fields.Date(compute='_compute_dates', string='From')
    date_to = fields.Date(compute='_compute_dates', string='To')
    employee_ids = fields.Many2many(
        'hr.employee', string='Employees',
        help="Leave empty to export every employee having timesheets in the period.")
    absence_task_ids = fields.Many2many(
        'project.task', string='Absence tasks', default=_default_absence_tasks,
        help="Timesheets on these tasks (and the ones generated by time off) are reported "
             "on the \"Absence / Congés\" row, which is excluded from the yearly total.")
    zip_file = fields.Binary(string='ZIP file', readonly=True, attachment=False)
    zip_filename = fields.Char(readonly=True)

    @api.depends('year', 'month')
    def _compute_dates(self):
        for wizard in self:
            if wizard.year and wizard.month:
                wizard.date_from, wizard.date_to = self.env['hr.timesheet.cir.export']._period_bounds(
                    wizard.year, wizard.month)
            else:
                wizard.date_from = wizard.date_to = False

    @api.constrains('year', 'month')
    def _check_period(self):
        for wizard in self:
            if not (2000 <= int(wizard.year) <= 2100 and 1 <= int(wizard.month) <= 12):
                raise ValidationError(_("Invalid year or month."))

    def action_export(self):
        """Generate the ZIP and trigger its download."""
        self.ensure_one()
        content, filename = self.env['hr.timesheet.cir.export']._generate_zip(
            int(self.year), int(self.month), self.employee_ids, self.absence_task_ids)
        self.write({'zip_file': base64.b64encode(content), 'zip_filename': filename})
        return {
            'type': 'ir.actions.act_url',
            'url': '/web/content/%s/%d/zip_file/%s?download=true' % (self._name, self.id, filename),
            'target': 'download',
            'close': True,
        }

    @api.model
    def is_export_button_visible(self, action_id):
        """Called by the web client: whether the control panel download
        button must be shown for ``action_id`` (the "All Timesheets" action)."""
        if not action_id or not self.env.user.has_group(ADMIN_GROUP):
            return False
        action = self.env.ref('hr_timesheet.timesheet_action_all', raise_if_not_found=False)
        return bool(action) and action.id == int(action_id)
